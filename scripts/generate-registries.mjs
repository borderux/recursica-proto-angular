// Angular's esbuild-based builder has no equivalent to Vite's
// `import.meta.glob`, so folder-based auto-discovery (prototypes, mock
// data, mock APIs) is instead resolved here, once, before dev/build, into
// plain generated TS files with static imports. See ARCHITECTURE.md.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(fileURLToPath(import.meta.url), "../..");
const appDir = path.join(root, "src/app");

function discoverFolders(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => existsSync(path.join(dir, name, "index.ts")))
    .sort();
}

function writeGenerated(filePath, contents) {
  const banner =
    "// GENERATED by scripts/generate-registries.mjs — do not hand-edit.\n" +
    "// Regenerated automatically before `npm run dev` / `npm run build`.\n\n";
  writeFileSync(filePath, banner + contents);
}

// --- Mock data registry -----------------------------------------------
{
  const dataDir = path.join(appDir, "data");
  const names = discoverFolders(dataDir);
  const imports = names.map((name, i) => `import * as dataset${i} from "./${name}";`).join("\n");
  const entries = names
    .map((name, i) => `  { name: ${JSON.stringify(name)}, description: dataset${i}.description },`)
    .join("\n");
  writeGenerated(
    path.join(dataDir, "registry.generated.ts"),
    `${imports}\n\nexport const mockDatasets = [\n${entries}\n];\n`,
  );
}

// --- Mock API registry --------------------------------------------------
{
  const apiDir = path.join(appDir, "api");
  const names = discoverFolders(apiDir);
  const imports = names.map((name, i) => `import * as api${i} from "./${name}";`).join("\n");
  const apiEntries = names
    .map((name, i) => `  { name: ${JSON.stringify(name)}, description: api${i}.description },`)
    .join("\n");
  const handlerSpreads = names.map((_, i) => `  ...api${i}.handlers,`).join("\n");
  writeGenerated(
    path.join(apiDir, "registry.generated.ts"),
    `${imports}\n\n` +
      `export const mockApis = [\n${apiEntries}\n];\n\n` +
      `export const apiHandlers = [\n${handlerSpreads}\n];\n`,
  );
}

// --- Prototype route registry --------------------------------------------
{
  const prototypesDir = path.join(appDir, "prototypes");
  const slugs = discoverFolders(prototypesDir);
  const entries = slugs
    .map(
      (slug) =>
        `  {\n` +
        `    slug: ${JSON.stringify(slug)},\n` +
        `    loadComponent: () => import("./${slug}").then((m) => m.default),\n` +
        `    loadMeta: () => import("./${slug}").then((m) => m.meta),\n` +
        `  },`,
    )
    .join("\n");
  writeGenerated(
    path.join(prototypesDir, "registry.generated.ts"),
    `import type { Type } from "@angular/core";\n\n` +
      `interface PrototypeMeta {\n  title?: string;\n  description?: string;\n}\n\n` +
      `interface DiscoveredPrototype {\n` +
      `  slug: string;\n` +
      `  loadComponent: () => Promise<Type<unknown>>;\n` +
      `  loadMeta: () => Promise<PrototypeMeta | undefined>;\n` +
      `}\n\n` +
      `export const discoveredPrototypes: DiscoveredPrototype[] = [\n${entries}\n];\n`,
  );
}

console.log("generate-registries: regenerated data/api/prototype registries");
